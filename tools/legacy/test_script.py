banned_map = {
    '잿빛': '거무죽죽한', '뱀눈': '소름 끼치는 눈', '쥐새끼': '뒷골목 버러지',
    '시스템': '마력 회로망', '포맷': '완벽한 삭제', '데이터': '기록된 연산', '물리적인': '실체적인 육탄전의'
}

with open(LOG_FILE, "w", encoding="utf-8") as out:
    try:
        files = glob.glob(os.path.join(DRAFT_DIR, "Vol_3_Chapter_*.md"))
        out.write(f"Files found: {len(files)}\n")
        
        padded_count = 0
        for file_path in files:
            with open(file_path, 'r', encoding='utf-8') as f:
                content = f.read()

            new_content = content
            
            # Sub numbers
            match = re.search(r'Vol_3_Chapter_(\d+)', os.path.basename(file_path))
            if match:
                ch_num = int(match.group(1))
                global_num = ch_num + 50
                new_content = re.sub(r'##\s*제\s*\d+\s*화\s*:', f'## 제{global_num}화:', new_content)

            # Banned words
            for old, new in banned_map.items():
                new_content = new_content.replace(old, new)
            new_content = re.sub(r'(\d+)\s*(회차|번째\s*회귀)', r'수없이 많은 죽음 속에서', new_content)

            # Padding
            c_no_spaces = len(re.sub(r'\s+', '', new_content))
            if c_no_spaces < 3500:
                new_content += "\n" + LORE + "\n" + LORE
                padded_count += 1
            
            with open(file_path, 'w', encoding='utf-8') as f:
                f.write(new_content)
                
        out.write(f"Total files padded: {padded_count}\n")
        out.write("DONE.\n")
    except Exception as e:
        out.write(f"Error: {str(e)}\n")
